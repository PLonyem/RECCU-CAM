export function translateText(language: Language, value: string): string {
  return language === "fr" ? frenchUi[value] ?? value : value;
}

export function formatDate(value: Date | string | number, language: Language, options?: Intl.DateTimeFormatOptions) {
  return new Intl.DateTimeFormat(language === "fr" ? "fr-CM" : "en-CM", options ?? { dateStyle: "long" }).format(new Date(value));
}

export function formatNumber(value: number, language: Language, options?: Intl.NumberFormatOptions) {
  return new Intl.NumberFormat(language === "fr" ? "fr-CM" : "en-CM", options).format(value);
}

