export function translateText(language: Language, value: string): string {
  return language === "fr" ? frenchUi[value] ?? value : value;
}

export function hasFrenchTranslation(value: string): boolean {
  return Object.hasOwn(frenchUi, value);
}

export function translateAdminText(language: Language, value: string): string {
  if (language === "en" || !value) return value;
  const direct = translateText(language, value);
  if (direct !== value || hasFrenchTranslation(value)) return direct;
  const sentenceCase = `${value.charAt(0).toUpperCase()}${value.slice(1)}`;
  const normalized = translateText(language, sentenceCase);
  if (normalized !== sentenceCase || hasFrenchTranslation(sentenceCase)) return normalized;

  const countPatterns: Array<[RegExp, (count: string) => string]> = [
    [/^(\d+) drafts?$/, (count) => `${count} brouillon${count === "1" ? "" : "s"}`],
    [/^(\d+) published documents?$/, (count) => `${count} document${count === "1" ? " publié" : "s publiés"}`],
    [/^(\d+) upcoming programmes?$/, (count) => `${count} programme${count === "1" ? " à venir" : "s à venir"}`],
    [/^(\d+) active$/, (count) => `${count} actif${count === "1" ? "" : "s"}`],
    [/^(\d+) marked urgent$/, (count) => `${count} signalé${count === "1" ? "" : "s"} comme urgent${count === "1" ? "" : "s"}`],
  ];
  for (const [pattern, translate] of countPatterns) {
    const match = value.match(pattern);
    if (match) return translate(match[1]);
  }
  return value;
}

export function formatDate(value: Date | string | number, language: Language, options?: Intl.DateTimeFormatOptions) {
  return new Intl.DateTimeFormat(language === "fr" ? "fr-CM" : "en-CM", options ?? { dateStyle: "long" }).format(new Date(value));
}

export function formatNumber(value: number, language: Language, options?: Intl.NumberFormatOptions) {
  return new Intl.NumberFormat(language === "fr" ? "fr-CM" : "en-CM", options).format(value);
}

