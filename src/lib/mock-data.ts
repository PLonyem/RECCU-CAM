// Mock data for the CamCCUL website prototype.
// All placeholder values are wrapped in square brackets and are intended to be
// obviously fake — CamCCUL staff must replace them with real institutional data
// before launch. Affiliate names are systematically generated (not real credit
// union names) to demonstrate the directory layout at production scale.
// NOTE: the regional distribution below sums to 216 affiliates, not 220 — the
// per-region counts as specified add up to 216.
//
// Per-affiliate fields (city/address/phone/email) are intentionally left as
// English placeholder brackets rather than translated — with 216 systematically
// generated entries all sharing the same "[City Name]"-style filler, a
// bilingual duplicate of identical placeholder text adds no value and will be
// replaced wholesale once CamCCUL provides real affiliate data. Structural/UI
// text and genuinely distinct content (milestones, leadership, news,
// resources, services) are fully bilingual below.

import type { LocalizedText } from "./i18n";

export interface Affiliate {
  id: string;
  code: string;
  name: string;
  region: string;
  city: string;
  address: string;
  phone: string;
  email: string;
  isActive: boolean;
}

export interface ContactInfo {
  address: string;
  phone: string;
  email: string;
  officeHours: LocalizedText;
}

export interface LeadershipMember {
  name: LocalizedText;
  title: LocalizedText;
  bio: LocalizedText;
}

export interface NewsArticleAuthor {
  name: string;
  role: string;
  photo: string;
}

export interface NewsArticleHeroImage {
  url: string;
  alt: string;
  caption: string;
}

export type NewsCategory =
  | "network-news"
  | "projects"
  | "training-events"
  | "insights"
  | "Circular"
  | "Training"
  | "COBAC"
  | "Announcement"
  | "Event";

export interface NewsArticle {
  id: string;
  title: string;
  slug: string;
  language: "en" | "fr";
  translationOf?: string;
  category: NewsCategory;
  tags: string[];
  excerpt: string;
  content: string;
  author: NewsArticleAuthor;
  publishedAt: string;
  chapter?: string;
  featured: boolean;
  heroImage: NewsArticleHeroImage;
}

export interface Resource {
  id: string;
  title: LocalizedText;
  description: LocalizedText;
  category: string;
  fileType: string;
  fileSize: number;
  downloadCount: number;
  fileUrl?: string;
}

export interface Service {
  icon: string;
  title: string;
  description: string;
  href: string;
}

export interface Milestone {
  year: string;
  title: LocalizedText;
  description: LocalizedText;
}

